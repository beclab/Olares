func TestHeaderReadsSetCookieAttributes(t *testing.T) {
	text := "Set-Cookie: SID=sid-value; Domain=.youtube.com; Path=/x; Secure; HttpOnly; SameSite=None; Expires=Wed, 21 Oct 2026 07:28:00 GMT"

	res, _, err := Parse(text, FormatHeader, "")
	if err != nil {
		t.Fatalf("parse: %v", err)
	}
	rec := recordByName(t, res, ".youtube.com", "SID")
	if !rec.Secure || !rec.HttpOnly {
		t.Errorf("flags: secure=%v httpOnly=%v, want both true", rec.Secure, rec.HttpOnly)
	}
	if rec.SameSite != "None" {
		t.Errorf("sameSite = %q, want None", rec.SameSite)
	}
	if rec.Path != "/x" {
		t.Errorf("path = %q, want /x", rec.Path)
	}
	want := time.Date(2026, 10, 21, 7, 28, 0, 0, time.UTC).Unix()
	if rec.ExpiryUnix() != want {
		t.Errorf("expires = %d, want %d", rec.ExpiryUnix(), want)
	}
}

