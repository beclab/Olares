func TestExpiryIsWrittenToBothFieldNames(t *testing.T) {
	res, _, err := Parse(netscapeLine(".example.com", "a", "b", "1780000000"), FormatNetscape, "")
	if err != nil {
		t.Fatalf("parse: %v", err)
	}
	rec := recordByName(t, res, ".example.com", "a")
	if rec.Expires != 1780000000 {
		t.Errorf("Expires = %v, want 1780000000", rec.Expires)
	}
	// download-server and the yt-dlp daemon read expirationDate, not expires.
	if rec.ExpirationDate != rec.Expires {
		t.Errorf("ExpirationDate = %v, want %v", rec.ExpirationDate, rec.Expires)
	}
}

// The SPA stores Date.now()/1000, so records already in Infisical carry
// fractional seconds. Decoding them must not fail.
func TestRecordDecodesAFractionalExpiry(t *testing.T) {
	var rec Record
	raw := `{"domain":".youtube.com","name":"SID","value":"v","expires":1800711300.517479}`
	if err := json.Unmarshal([]byte(raw), &rec); err != nil {
		t.Fatalf("unmarshal: %v", err)
	}
	if got := rec.ExpiryUnix(); got != 1800711300 {
		t.Errorf("ExpiryUnix = %d, want 1800711300", got)
	}
}

func TestJSONParsesExtensionExports(t *testing.T) {
	text := `[
		{"domain":".youtube.com","name":"SID","value":"sid","path":"/","secure":true,"httpOnly":true,"expirationDate":1780000000.75},
		{"domain":".youtube.com","name":"PREF","value":"tz","expires":1770000000}
	]`

	res, format, err := Parse(text, FormatAuto, "")
	if err != nil {
		t.Fatalf("parse: %v", err)
	}
	if format != FormatJSON {
		t.Fatalf("detected format = %q, want json", format)
	}

	sid := recordByName(t, res, ".youtube.com", "SID")
	if !sid.HttpOnly || !sid.Secure {
		t.Errorf("SID flags: httpOnly=%v secure=%v, want both true", sid.HttpOnly, sid.Secure)
	}
	if sid.ExpiryUnix() != 1780000000 {
		t.Errorf("SID expires = %d, want 1780000000 (truncated from expirationDate)", sid.ExpiryUnix())
	}
	if pref := recordByName(t, res, ".youtube.com", "PREF"); pref.ExpiryUnix() != 1770000000 {
		t.Errorf("PREF expires = %d, want 1770000000", pref.ExpiryUnix())
	}
}

