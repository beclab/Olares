func netscapeLine(domain, name, value, expires string) string {
	return strings.Join([]string{domain, "TRUE", "/", "TRUE", expires, name, value}, "\t")
}

func recordByName(t *testing.T, res *Result, domain, name string) Record {
	t.Helper()
	for _, r := range res.Cookies[domain] {
		if r.Name == name {
			return r
		}
	}
	t.Fatalf("no cookie %q under domain %q (have %+v)", name, domain, res.Cookies)
	return Record{}
}

func TestNetscapeKeepsHTTPOnlyRecords(t *testing.T) {
	text := strings.Join([]string{
		"# Netscape HTTP Cookie File",
		"# This file is generated by yt-dlp.  Do not edit.",
		"",
		netscapeLine(".youtube.com", "PREF", "tz=Asia.Shanghai", "1780000000"),
		netscapeLine("#HttpOnly_.youtube.com", "SID", "sid-value", "1780000000"),
		netscapeLine("#HttpOnly_.youtube.com", "__Secure-3PSID", "psid-value", "1780000000"),
		netscapeLine("#HttpOnly_.youtube.com", "HSID", "hsid-value", "1780000000"),
	}, "\n")

	res, format, err := Parse(text, FormatAuto, "")
	if err != nil {
		t.Fatalf("parse: %v", err)
	}
	if format != FormatNetscape {
		t.Fatalf("detected format = %q, want netscape", format)
	}
	if len(res.InvalidLines) != 0 {
		t.Fatalf("unexpected invalid lines: %v", res.InvalidLines)
	}
	if got := res.Count(); got != 4 {
		t.Fatalf("parsed %d records, want 4 (httpOnly records must survive)", got)
	}

	for _, name := range []string{"SID", "__Secure-3PSID", "HSID"} {
		if rec := recordByName(t, res, ".youtube.com", name); !rec.HttpOnly {
			t.Errorf("cookie %q: HttpOnly = false, want true", name)
		}
	}
	if rec := recordByName(t, res, ".youtube.com", "PREF"); rec.HttpOnly {
		t.Error("cookie PREF: HttpOnly = true, want false")
	}
}

