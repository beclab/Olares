package userspace

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"github.com/beclab/Olares/framework/app-service/pkg/constants"
)

// GetSysApps get all system apps from env
func GetSysApps() []string {
	sysAppsEnv := os.Getenv("SYS_APPS")
	return strings.Split(sysAppsEnv, ",")
}

// GetKbMiddlewares from env
func GetKbMiddlewares() []string {
	kbMiddlewaresEnv := os.Getenv("KB_MIDDLEWARES")
	return strings.Split(kbMiddlewaresEnv, ",")
}

func IsKbMiddlewares(middleware string) bool {
	kbMiddlewares := GetKbMiddlewares()
	for _, name := range kbMiddlewares {
		if name == middleware {
			return true
		}
	}
	return false
}

// IsSysApp returns true if app is system app, false otherwise.
func IsSysApp(appName string) bool {
	sysApps := GetSysApps()
	for _, app := range sysApps {
		if app == appName {
			return true
		}
	}
	return false
}

// IsGeneratedApp checks if an app is generated by terminus system.
func IsGeneratedApp(name string) bool {
	generatedAppsEnv := os.Getenv("GENERATED_APPS")
	generatedApps := strings.Split(generatedAppsEnv, ",")
	for _, a := range generatedApps {
		if strings.HasPrefix(name, a) {
			return true
		}
	}
	return false
}

// UserChartRoot pins the published snapshot for a Helm operation. The legacy
// layout remains readable until the installer publishes the first snapshot.
func UserChartRoot() (string, error) {
	return userChartRoot(constants.UserChartsPath)
}

func userChartRoot(root string) (string, error) {
	target, err := os.Readlink(filepath.Join(root, "current"))
	if os.IsNotExist(err) {
		return root, nil
	}
	if err != nil {
		return "", fmt.Errorf("read current user chart bundle: %w", err)
	}
	if filepath.Base(target) != target || !strings.HasPrefix(target, ".bundle.") ||
		len(target) != len(".bundle.XXXXXXXX") {
		return "", fmt.Errorf("invalid current user chart bundle")
	}
	snapshot := filepath.Join(root, target)
	info, err := os.Lstat(snapshot)
	if err != nil {
		return "", fmt.Errorf("read user chart bundle: %w", err)
	}
	if !info.IsDir() {
		return "", fmt.Errorf("current user chart bundle is not a directory")
	}
	return snapshot, nil
}

// GetAppsFromDirectory returns all system applications.
func GetAppsFromDirectory(directory string) ([]string, error) {
	subDirectories := make([]string, 0)
	dirEntries, err := os.ReadDir(directory)
	if err != nil {
		return nil, err
	}

	for _, entry := range dirEntries {
		if entry.IsDir() && !strings.HasPrefix(entry.Name(), ".") {
			subDirectories = append(subDirectories, entry.Name())
		}
	}
	return subDirectories, nil
}
